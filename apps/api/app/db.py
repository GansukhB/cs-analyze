from collections.abc import Iterator

from sqlalchemy import MetaData, create_engine
from sqlalchemy.orm import DeclarativeBase, Session, sessionmaker

from app.config import get_settings

# Sync on purpose: the Celery worker shares these models and sessions with the API.
# READ COMMITTED (Django's MySQL default, which cstat's code assumed): a worker session
# open across a long job must see rows the API commits meanwhile, and vice versa.
_url = get_settings().database_url
engine = create_engine(
    _url,
    pool_pre_ping=True,
    **({"isolation_level": "READ COMMITTED"} if _url.startswith("mysql") else {}),
)
SessionLocal = sessionmaker(bind=engine, expire_on_commit=False)

# Deterministic constraint names, so autogenerated migrations can drop what they create.
# Multi-column unique constraints are named by hand: the full column list would exceed
# MySQL's 64-character identifier limit.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def get_db() -> Iterator[Session]:
    with SessionLocal() as session:
        yield session
